#!/usr/bin/env python3
"""Generate one documentation page per NPF module for the npf-docs site.

Every non-deprecated ``modules/*.npf`` file becomes a MyST Markdown page,
``<output>/<module>.md``, made of:

* the ``%info`` section, passed through as Markdown. It is read the way NPF
  reads it: ``//`` comments are removed and a line starting with ``%%`` stands
  for a line starting with ``%`` (so ``%%import@client foo`` documents an
  import without starting a section). Headings are shifted so the module name
  is the only top-level title. The first line is also the test title NPF uses
  in graphs and notebooks, so keep it a plain sentence;
* a table of the ``%variables``, with their default value, the values they
  take under some tags, and a description. The description is the ``//``
  comment on the line(s) right above the variable, or the ``//`` comment at
  the end of its line. It describes that variable only, not the next ones: a
  comment about a group of variables must be followed by an empty line, so it
  is not taken as the description of the first variable of the group.
  Commented-out assignments (``//VAR=value``) are not descriptions;
* the same for ``%late_variables``, folded;
* the manual notes of the page. Everything below the NOTES marker of an
  existing page is kept as is, so the npf-docs maintainers can complete a page
  without the next generation erasing it.

A module is deprecated when one of the first 3 lines of its ``%info`` says so.
Pages of modules that are deleted or deprecated are removed, unless they have
manual notes.

The CI of NPF (.github/workflows/module-docs.yml) runs this script at every
push to main and pushes the result to github.com/tbarbette/npf-docs.

Usage:
    python3 modules/generate_doc.py [--output DIR]

The default output is ../npf-docs/docs/source/modules/ (relative to the NPF
root). The index page modules.rst of npf-docs picks the pages up with a glob.
"""

import argparse
import os
import re
import subprocess
import sys
from collections import OrderedDict

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
NPF_ROOT = os.path.dirname(SCRIPT_DIR)
DEFAULT_OUTPUT = os.path.join(NPF_ROOT, "..", "npf-docs", "docs", "source", "modules")
SOURCE_URL = "https://github.com/tbarbette/npf/blob/main/modules/{}.npf"

# First line of every generated page, used to recognize generated pages
GENERATED_TAG = "% AUTO-GENERATED by modules/generate_doc.py"
# Everything after this line is kept when a page is regenerated
NOTES_MARKER = ("% ===== NOTES: everything below this line is kept when the page is regenerated. "
                "Write manual notes here, for instance under a \"## Notes\" heading. =====")
# Pages generated in RST by the first version of this script
LEGACY_RST_TAG = ".. Auto-generated by modules/generate_doc.py"

VALUE_MAX_LEN = 60

# Same as npf.models.variables.variable.Variable and npf.tests.test.Test
NAME_REGEX = r'[a-zA-Z0-9._-]+'
TAGS_REGEX = r'[a-zA-Z0-9._,|!-]+'
VARIABLE_RE = re.compile(
    r'^(?:(?P<tags>' + TAGS_REGEX + r'):)?(?P<name>' + NAME_REGEX + r')(?P<assign>=|[+?]=)(?P<value>.*)$')
SECTION_RE = re.compile(r'^%(?:(?P<tags>' + TAGS_REGEX + r'):)?(?P<name>[a-z_]+)')
COMMENT_RE = re.compile(r'(^|[ ])//(?P<comment>.*)$')


def warn(message, path=None):
    if os.environ.get("GITHUB_ACTIONS"):
        print("::warning%s::%s" % (" file=" + path if path else "", message))
    else:
        print("WARNING: " + message, file=sys.stderr)


# --------------------------------------------------------------------------
# Reading .npf files
# --------------------------------------------------------------------------

def read_sections(path):
    """Read an .npf file like NPF does.

    :return: a list of (section name, section tags, lines) where each line is a
             tuple (raw line, line as NPF sees it, i.e. without // comment)
    """
    sections = []
    current = None
    with open(path) as f:
        for raw in f.read().splitlines():
            line = COMMENT_RE.sub("", raw)
            if line.startswith("%"):
                if line[1:2] == "%":
                    line = line[1:]
                else:
                    m = SECTION_RE.match(line)
                    current = (m.group("name") if m else line[1:].split()[0], m.group("tags") if m else None, [])
                    sections.append(current)
                    continue
            if current is not None:
                current[2].append((raw, line))
    return sections


def section_text(sections, name):
    """Content of the given sections as NPF sees it (comments removed), stripped."""
    lines = [line for sname, _, content in sections if sname == name for _, line in content]
    return "\n".join(l.rstrip() for l in lines).strip("\n")


def is_deprecated(info):
    return any(re.search(r"deprecated", line, re.IGNORECASE) for line in info.splitlines()[:3])


def comment_text(comment):
    """Text of a // comment, or None if it is commented-out code or a banner."""
    text = comment.strip().lstrip("/").strip()
    if not text or re.fullmatch(r"[\W_]+", text) or re.search(r"(-{4,}|={4,})", text):
        return None
    if VARIABLE_RE.match(text) and " " not in text.split("=")[0]:
        return None  # A commented-out variable
    return text


def parse_variables(sections, name):
    """Variables of all sections called name, in order of appearance.

    :return: an OrderedDict name -> {"assignments": [(tags, assign, value)], "description": str}
    """
    variables = OrderedDict()
    for sname, stags, content in sections:
        if sname != name:
            continue
        pending = []
        for raw, line in content:
            stripped = raw.strip()
            if not stripped or stripped == "}":
                pending = []
                continue
            if stripped.startswith("//"):
                text = comment_text(stripped)
                if text:
                    pending.append(text)
                else:
                    pending = []
                continue
            m = VARIABLE_RE.match(line.strip())
            if not m:
                pending = []
                continue
            trailing = COMMENT_RE.search(raw.strip())
            description = " ".join(pending) or (comment_text(trailing.group("comment")) if trailing else None)
            pending = []
            tags = [t for t in (stags, m.group("tags")) if t]
            var = variables.setdefault(m.group("name"), {"assignments": [], "description": None})
            var["assignments"].append((tags, m.group("assign"), m.group("value").strip()))
            if description and not var["description"]:
                var["description"] = description
    return variables


def module_list():
    """Module names, from git when possible so untracked files are ignored."""
    try:
        out = subprocess.run(["git", "-C", NPF_ROOT, "ls-files", "-z", "modules"],
                             check=True, capture_output=True, text=True).stdout
        files = [os.path.basename(f) for f in out.split("\0") if f]
    except (OSError, subprocess.CalledProcessError):
        files = os.listdir(SCRIPT_DIR)
    return sorted(f[:-len(".npf")] for f in files if f.endswith(".npf"))


# --------------------------------------------------------------------------
# Markdown rendering
# --------------------------------------------------------------------------

def code(text):
    """Inline code span for text, safe in a table cell."""
    ticks = "`" * (max((len(r) for r in re.findall(r"`+", text)), default=0) + 1)
    pad = " " if text.startswith("`") or text.endswith("`") else ""
    return (ticks + pad + text + pad + ticks).replace("|", "\\|")


def split_code_spans(line):
    """Split a line in (is_code, text) parts."""
    parts = []
    pos = 0
    for m in re.finditer(r"(`+)(.+?)(?<!`)\1(?!`)", line):
        if m.start() > pos:
            parts.append((False, line[pos:m.start()]))
        parts.append((True, m.group(0)))
        pos = m.end()
    if pos < len(line):
        parts.append((False, line[pos:]))
    return parts


def escape_text(text):
    """Escape what Markdown would hide: raw HTML such as <role> in RESULT-<role>."""
    autolink = re.compile(r"<(?:[a-zA-Z][a-zA-Z0-9+.-]*:[^\s<>]*|[^\s<>@]+@[^\s<>]+)>")
    out = []
    pos = 0
    for m in autolink.finditer(text):
        out.append(re.sub(r"<(?=[a-zA-Z/!?])", r"\\<", text[pos:m.start()]))
        out.append(m.group(0))
        pos = m.end()
    out.append(re.sub(r"<(?=[a-zA-Z/!?])", r"\\<", text[pos:]))
    return "".join(out)


def linkify(text, module_names, current):
    """Link mentions of other modules, `name` or a bare name that cannot be a plain word."""
    def link_code(m):
        name = m.group(1)
        if name in module_names and name != current:
            return "[`%s`](%s.md)" % (name, name)
        return m.group(0)

    def link_bare(m):
        name = m.group(1)
        if name in module_names and name != current and re.search(r"[-_0-9]", name):
            return "[%s](%s.md)" % (name, name)
        return m.group(0)

    parts = []
    for is_code, part in split_code_spans(text):
        if is_code:
            parts.append(re.sub(r"^`([^`]+)`$", link_code, part))
        else:
            part = escape_text(part)
            parts.append(re.sub(r"(?<![\w./\\-])(" + NAME_REGEX + r")(?![\w/-]|\.\w)", link_bare, part))
    return "".join(parts)


def render_info(info, module_names, current):
    """%info as Markdown: headings shifted under the page title, % lines escaped, modules linked."""
    lines = info.splitlines()
    fence = None
    levels = []
    for line in lines:
        f = re.match(r"^\s*(`{3,}|~{3,})", line)
        if fence:
            if f and f.group(1)[0] == fence[0] and len(f.group(1)) >= len(fence):
                fence = None
        elif f:
            fence = f.group(1)
        else:
            h = re.match(r"^(#{1,6})\s", line)
            if h:
                levels.append(len(h.group(1)))
    shift = 2 - min(levels) if levels else 0

    out = []
    fence = None
    for line in lines:
        f = re.match(r"^\s*(`{3,}|~{3,})", line)
        if fence:
            if f and f.group(1)[0] == fence[0] and len(f.group(1)) >= len(fence):
                fence = None
            out.append(line)
            continue
        if f:
            fence = f.group(1)
            out.append(line)
            continue
        if line.startswith("    ") or line.startswith("\t"):
            out.append(line)  # Indented code block (or paragraph continuation)
            continue
        h = re.match(r"^(#{1,6})(\s.*)$", line)
        if h:
            level = min(6, len(h.group(1)) + shift)
            out.append("#" * level + h.group(2))
            continue
        if line.startswith("%"):
            line = "\\" + line  # Else it is a MyST comment
        out.append(linkify(line, module_names, current))
    return "\n".join(out)


def describe_tags(tags):
    """Human-readable NPF tag condition, e.g. "a,-b|c" -> `a` and not `b`, or `c`."""
    def one(expr):
        ors = []
        for group in expr.split("|"):
            ands = []
            for t in group.split(","):
                if t.startswith("-") or t.startswith("!"):
                    ands.append("not %s" % code(t[1:]))
                else:
                    ands.append(code(t))
            ors.append(" and ".join(ands))
        return ", or ".join(ors)

    parts = [one(t) for t in tags]
    if len(parts) > 1:
        parts = ["(%s)" % p if ", or " in p else p for p in parts]
    return " and ".join(parts)


def show_value(value):
    if value == "":
        return "*empty*"
    if len(value) > VALUE_MAX_LEN:
        value = value[:VALUE_MAX_LEN - 1].rstrip() + "…"
    return code(value)


def variables_table(variables):
    rows = ["| Variable | Default | Description |", "|---|---|---|"]
    for name, var in variables.items():
        values = []
        # The value without tags first, then the values under some tags, that take precedence
        for tags, assign, value in sorted(var["assignments"], key=lambda a: bool(a[0])):
            v = show_value(value)
            if assign == "+=":
                v = "appends " + v
            if tags:
                v = "%s with %s" % (v, describe_tags(tags))
            values.append(v)
        description = var["description"] or ""
        rows.append("| %s | %s | %s |" % (code(name), "<br>".join(values),
                                          escape_text(description).replace("|", "\\|")))
    return "\n".join(rows)


def render_page(name, info, variables, late_variables, module_names, notes):
    path = "modules/%s.npf" % name
    out = [
        GENERATED_TAG + " from " + path + " of the NPF repository,",
        "% at every commit to NPF's main branch.",
        "% DO NOT EDIT above the NOTES marker at the end of this file: the next generation",
        "% would overwrite it. Edit the %info section and the // comments of the variables",
        "% in " + path + " instead.",
        "% Manual notes are welcome BELOW the NOTES marker: they are kept.",
        "",
        "# " + name,
        "",
    ]
    if info:
        out += [render_info(info, module_names, name), ""]
    else:
        out += ["*No description available.*", ""]
    out += ["Source: [`%s`](%s)" % (path, SOURCE_URL.format(name)), ""]

    out += ["## Variables", ""]
    if variables:
        out += [variables_table(variables), ""]
    else:
        out += ["This module defines no variables.", ""]
    if late_variables:
        out += [
            "```{collapse} Late variables",
            "",
            "Late variables are evaluated after the variables above.",
            "",
            variables_table(late_variables),
            "```",
            "",
        ]
    out.append(NOTES_MARKER)
    page = "\n".join(out) + "\n"
    if notes:
        page += notes
    return page


# --------------------------------------------------------------------------
# Main
# --------------------------------------------------------------------------

def read_notes(path):
    """Manual notes of an existing page: None if the page has no NOTES marker."""
    with open(path) as f:
        content = f.read()
    idx = content.find(NOTES_MARKER)
    if idx < 0:
        return None
    return content[idx + len(NOTES_MARKER):].lstrip("\n")


def is_generated(path, tag):
    with open(path) as f:
        return f.readline().startswith(tag)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--output", default=DEFAULT_OUTPUT,
                        help="npf-docs folder of module pages (default: %(default)s)")
    args = parser.parse_args()
    output_dir = os.path.normpath(args.output)
    os.makedirs(output_dir, exist_ok=True)

    modules = OrderedDict()
    deprecated = []
    for name in module_list():
        sections = read_sections(os.path.join(SCRIPT_DIR, name + ".npf"))
        info = section_text(sections, "info")
        if is_deprecated(info):
            deprecated.append(name)
            continue
        modules[name] = sections
    module_names = set(modules)

    written = 0
    for name, sections in modules.items():
        page_path = os.path.join(output_dir, name + ".md")
        notes = ""
        if os.path.exists(page_path):
            notes = read_notes(page_path)
            if notes is None:
                warn("%s has no NOTES marker, it was not regenerated so as not to lose manual edits. "
                     "Put the marker back above the manual part." % page_path, page_path)
                continue
        legacy = os.path.join(output_dir, name + ".rst")
        if os.path.exists(legacy):
            if is_generated(legacy, LEGACY_RST_TAG):
                os.remove(legacy)
            else:
                warn("%s is not generated, remove it or merge it in %s.md" % (legacy, name), legacy)
        page = render_page(name,
                           section_text(sections, "info"),
                           parse_variables(sections, "variables"),
                           parse_variables(sections, "late_variables"),
                           module_names, notes)
        with open(page_path, "w") as f:
            f.write(page)
        written += 1

    # Pages of modules that are removed or deprecated
    removed = []
    for f in sorted(os.listdir(output_dir)):
        name, ext = os.path.splitext(f)
        path = os.path.join(output_dir, f)
        if name in module_names:
            continue
        if ext == ".md" and is_generated(path, GENERATED_TAG):
            if read_notes(path):
                warn("module %s is gone or deprecated, but %s has manual notes and was kept" % (name, path), path)
                continue
        elif not (ext == ".rst" and is_generated(path, LEGACY_RST_TAG)):
            continue
        os.remove(path)
        removed.append(f)

    print("Generated %d pages in %s" % (written, output_dir))
    print("  %d deprecated modules skipped: %s" % (len(deprecated), ", ".join(deprecated)))
    if removed:
        print("  Removed stale pages: %s" % ", ".join(removed))


if __name__ == "__main__":
    main()
